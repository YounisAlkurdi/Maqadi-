export function suggestCategory(text) {
  const normalized = (text || "").trim().toLowerCase();
  if (!normalized) return "other";
  for (const [category, words] of Object.entries(CATEGORY_KEYWORDS)) {
    if (words.some((w) => normalized.includes(w))) {
      return category;
    }
  }
  return "other";
}
